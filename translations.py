def translate_workbook(wb, target):
    """wb のラベル文字列セルを target ('ja'/'en') の言語へ置換する。"""
    if target not in ("ja", "en"):
        return
    mapping = EN_TO_JP if target == "ja" else JP_TO_EN
    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for c in row:
                v = c.value
                if not isinstance(v, str) or v.startswith("="):
                    continue
                key = v.strip()
                if key in mapping:
                    c.value = mapping[key]
